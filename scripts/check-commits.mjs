import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const policy = JSON.parse(readFileSync(new URL("../.commit-policy.json", import.meta.url), "utf8"));

export function validateMessage(message) {
  const [header, secondLine] = message.replace(/\r\n/g, "\n").split("\n");
  const match = /^([a-z]+)(?:\(([a-z0-9][a-z0-9./_-]*)\))?!?: (\S(?:.*\S)?)$/.exec(header);
  const errors = [];
  if (!match || !policy.types.includes(match[1]))
    errors.push(`Use type(scope): description. Allowed types: ${policy.types.join(", ")}.`);
  if ([...header].length > policy.headerMaxLength)
    errors.push(`The first line must contain at most ${policy.headerMaxLength} characters.`);
  if (
    [...header].some(
      (character) => character.codePointAt(0) < 32 || character.codePointAt(0) === 127,
    )
  )
    errors.push("The first line contains control characters.");
  if (secondLine !== undefined && secondLine.trim() !== "")
    errors.push("Separate the description from the body with a blank line.");
  return errors;
}

function git(args, cwd = process.cwd()) {
  return execFileSync("git", args, {
    cwd,
    encoding: "utf8",
    stdio: ["pipe", "pipe", "pipe"],
  }).trim();
}

export function checkHistory({ cwd = process.cwd(), base, head = "HEAD" } = {}) {
  const headSha = git(["rev-parse", "--verify", "--end-of-options", `${head}^{commit}`], cwd);
  let range = headSha;
  if (base !== undefined) {
    const baseSha = git(["rev-parse", "--verify", "--end-of-options", `${base}^{commit}`], cwd);
    const ancestor = git(["merge-base", baseSha, headSha], cwd);
    range = `${ancestor}..${headSha}`;
  }
  const commits = git(["rev-list", "--reverse", "--no-merges", range], cwd)
    .split("\n")
    .filter(Boolean);
  const failures = [];
  for (const sha of commits) {
    const message = git(["show", "-s", "--format=%B", sha], cwd);
    const errors = validateMessage(message);
    if (errors.length) failures.push({ sha, header: message.split("\n")[0], errors });
  }
  return { checked: commits.length, failures };
}

export function runCli(args) {
  if (args[0] === "--file" && args.length === 2) {
    // Real merge commits are generated by Git; ordinary commits cannot bypass the policy
    // merely by using a subject that starts with "Merge".
    if (existsSync(git(["rev-parse", "--git-path", "MERGE_HEAD"]))) return 0;
    const message = execFileSync("git", ["stripspace", "--strip-comments"], {
      input: readFileSync(args[1], "utf8"),
      encoding: "utf8",
    });
    const errors = validateMessage(message);
    if (errors.length) {
      console.error(errors.join("\n"));
      console.error("Example: fix(web): preserve messages during concurrent requests");
    }
    return errors.length ? 1 : 0;
  }

  let options = {};
  let titleErrors = [];
  if (args[0] === "--range" && args.length === 3) {
    options = { base: args[1], head: args[2] };
  } else if (args[0] === "--ci" && args.length === 1) {
    const event = JSON.parse(readFileSync(process.env.GITHUB_EVENT_PATH, "utf8"));
    if (event.pull_request) {
      options = { base: event.pull_request.base.sha, head: event.pull_request.head.sha };
      titleErrors = validateMessage(event.pull_request.title);
      for (const error of titleErrors) console.error(`PR title: ${error}`);
    }
  } else if (args.length) {
    throw new Error(
      "Usage: node scripts/check-commits.mjs [--file PATH | --range BASE HEAD | --ci]",
    );
  }
  const result = checkHistory(options);
  for (const failure of result.failures)
    console.error(`${failure.sha.slice(0, 8)} ${failure.header}\n${failure.errors.join("\n")}`);
  console.log(`Checked ${result.checked} commits; ${result.failures.length} invalid.`);
  return result.failures.length || titleErrors.length ? 1 : 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exitCode = runCli(process.argv.slice(2));
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
